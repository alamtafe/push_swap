#include "push_swap.h"

void	add_back(t_stack **stack, t_stack *new)
{
	t_stack *tmp;

	if (!stack)
		return ;
	if (!*stack)
	{
		*stack = new;
		return ;
	}
	tmp = *stack;
	while (tmp->next)
	{
		tmp = tmp->next;
	}
	tmp->next = new;
	return ;
}